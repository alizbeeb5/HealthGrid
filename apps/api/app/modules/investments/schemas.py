"""Shared Feature 7 investment contract. Owner: backend/data (engine owner reviews
numerical fields). See docs/feature-7-contract.md.

The engine interface is `optimize_investments(InvestmentEngineInput) ->
InvestmentEngineResult` in engines/investments.py; it imports these types. Statuses
and solver settings are shared with Feature 6. Results are funding proposals for
human review: they do not purchase equipment or approve a budget.
"""

