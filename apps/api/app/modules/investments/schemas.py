SCHEMA_VERSION = 1
PositiveCount = Annotated[int, Field(gt=0, strict=True)]


class CandidateExclusionReason(StrEnum):
    MISSING_CONFIRMATION = "missing_confirmation"  # no source_note/confirmed_at
    FACILITY_EXCLUDED = "facility_excluded"  # not an included source facility
    NOT_READY_BY_EVALUATION = "not_ready_by_evaluation"
    PREREQUISITE_INELIGIBLE = "prerequisite_ineligible"


# Candidates and request.


class ResourceEffect(ContractModel):
    resource_id: Identifier
    quantity_delta: Count  # nonnegative whole quantity added when commissioned
    unit: ResourceUnit


class InvestmentCandidate(ContractModel):
    """A supplied, human-reviewed project. Costs and times are estimates, never
    generated by the optimizer. Missing confirmation makes it ineligible."""

    candidate_id: Identifier
    name: str = Field(min_length=1, max_length=200)
    facility_id: Identifier
    service_id: Identifier
    capital_cost_minor_units: Count
    monthly_operating_cost_minor_units: Count
    implementation_days: Count = Field(le=36_500)  # bounded calendar planning horizon
    resource_effects: list[ResourceEffect] = Field(max_length=50)
    requires_candidate_ids: list[Identifier] = Field(max_length=100)
    exclusive_group_id: Identifier | None
    source_note: SourceNote | None
    confirmed_at: AwareDatetime | None

    @model_validator(mode="after")
    def well_formed(self) -> Self:
        effects = [e.resource_id for e in self.resource_effects]
        if len(effects) != len(set(effects)):
            raise ValueError("Duplicate resource effects.")
        if self.requires_candidate_ids != sorted(set(self.requires_candidate_ids)):
            raise ValueError("requires_candidate_ids must be sorted and unique.")
        if self.candidate_id in self.requires_candidate_ids:
            raise ValueError("A candidate cannot require itself.")
        return self


class InvestmentCatalog(ContractModel):
    """Versioned starter catalog; a request copies and may edit it run-locally."""

    catalog_version: str = Field(min_length=1, max_length=64)
    currency: Literal["USD"]
    synthetic: Literal[True]
    candidates: list[InvestmentCandidate]


class InvestmentRunRequest(ContractModel):
    allocation_run_id: Identifier
    planning_starts_at: AwareDatetime  # assumption: source transfers completed
    evaluation_at: AwareDatetime
    operating_cost_months: PositiveCount = Field(le=1200)
    budget_minor_units: Count  # USD cents, separate from transfer costs
    currency: Literal["USD"]
    catalog_version: str = Field(min_length=1, max_length=64)
    candidates: list[InvestmentCandidate] = Field(max_length=100)
    assumptions: list[SourceNote] = Field(max_length=100)

    @field_validator("candidates")
    @classmethod
    def unique_ids(cls, value: list[InvestmentCandidate]) -> list[InvestmentCandidate]:
        if len({c.candidate_id for c in value}) != len(value):
            raise ValueError("candidate_id values must be unique.")
        return value


