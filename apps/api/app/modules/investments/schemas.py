# Post-transfer frozen snapshot and inherited demand (null when excluded).
InvestmentFacilityInput = PostAllocationFacility


class InvestmentEngineInput(ContractModel):
    service_id: Identifier
    capacity_unit: CapacityUnit
    requirement: ServiceRequirement
    facilities: list[InvestmentFacilityInput]  # every source facility, by facility_id
    included_facility_ids: list[Identifier]  # inherited from the allocation
    excluded_facilities: list[FacilityExclusion]  # inherited, with reasons
    candidates: list[InvestmentCandidate]
    planning_starts_at: AwareDatetime
    evaluation_at: AwareDatetime
    operating_cost_months: PositiveCount
    budget_minor_units: Count
    currency: Literal["USD"]
    solver_settings: SolverSettings


class CandidateExclusion(ContractModel):
    candidate_id: Identifier
    reasons: list[CandidateExclusionReason] = Field(min_length=1)


class InvestmentCoverage(ContractModel):
    included_facility_ids: list[Identifier]
    excluded_facilities: list[FacilityExclusion]
    excluded_candidates: list[CandidateExclusion]

    @model_validator(mode="after")
    def sorted_unique(self) -> Self:
        for ids, name in (
            (self.included_facility_ids, "included_facility_ids"),
            ([e.facility_id for e in self.excluded_facilities], "excluded_facilities"),
            ([e.candidate_id for e in self.excluded_candidates], "excluded_candidates"),
        ):
            if ids != sorted(set(ids)):
                raise ValueError(f"{name} must be sorted and unique.")
        return self


class ResourceQuantity(ContractModel):
    resource_id: Identifier
    quantity: float = Field(ge=0, allow_inf_nan=False)


class InvestmentFacilityRow(ContractModel):
    facility_id: Identifier
    service_status: ServiceStatus
    required_service_places: Count
    resource_quantities: list[ResourceQuantity]  # profile resources, by resource_id
    estimated_capacity: Count
    covered_service_places: Count
    unmet_service_places: Count
    bottleneck_resource_ids: list[Identifier]

    @model_validator(mode="after")
    def consistent(self) -> Self:
        covered = min(self.estimated_capacity, self.required_service_places)
        if (self.covered_service_places, self.unmet_service_places) != (
            covered, self.required_service_places - covered
        ):
            raise ValueError("covered = min(capacity, required); unmet = required - covered.")
        ids = [q.resource_id for q in self.resource_quantities]
        if ids != sorted(set(ids)):
            raise ValueError("resource_quantities must be ordered by unique resource_id.")
        return self


class InvestmentSummary(ContractModel):
    """Totals over included facilities only at evaluation_at."""

    included_facility_ids: list[Identifier]
    required_service_places: Count
    covered_service_places: Count
    unmet_service_places: Count
    rows: list[InvestmentFacilityRow]

    @model_validator(mode="after")
    def totals(self) -> Self:
        ids = [row.facility_id for row in self.rows]
        if ids != self.included_facility_ids or ids != sorted(set(ids)):
            raise ValueError("One row per included facility, ordered by facility_id.")
        sums = (sum(r.required_service_places for r in self.rows),
                sum(r.covered_service_places for r in self.rows),
                sum(r.unmet_service_places for r in self.rows))
        if sums != (self.required_service_places, self.covered_service_places,
                    self.unmet_service_places):
            raise ValueError("Summary totals must equal the sum of rows.")
        return self


class SelectedProject(ContractModel):
    candidate_id: Identifier
    facility_id: Identifier
    ready_at: AwareDatetime
    requires_candidate_ids: list[Identifier]
    resource_effects: list[ResourceEffect]
    capital_cost_minor_units: Count
    operating_cost_minor_units: Count  # monthly cost x operating_cost_months
    total_cost_minor_units: Count

    @model_validator(mode="after")
    def total(self) -> Self:
        if self.total_cost_minor_units != (
            self.capital_cost_minor_units + self.operating_cost_minor_units
        ):
            raise ValueError("total = capital + operating allowance.")
        return self


class InvestmentEngineResult(ContractModel):
    engine_version: str = Field(min_length=1, max_length=64)
    solver_version: str = Field(min_length=1, max_length=64)
    solver_status: SolverStatus
    plan_outcome: PlanOutcome
    coverage: InvestmentCoverage
    baseline_summary: InvestmentSummary  # post-transfer, no further investment
    proposed_summary: InvestmentSummary | None
    selected_projects: list[SelectedProject]  # by candidate_id, prerequisites included
    total_capital_cost_minor_units: Count
    total_operating_cost_minor_units: Count
    total_cost_minor_units: Count
    remaining_budget_minor_units: Count
    remaining_gap_reasons: list[SourceNote]
    validation_passed: bool
    review_required: Literal[True]
    objective_description: str = Field(min_length=1, max_length=500)
    solve_duration_ms: Count

    @model_validator(mode="after")
    def consistent_outcome(self) -> Self:
        status, outcome, proposed = self.solver_status, self.plan_outcome, self.proposed_summary
        if (status == SolverStatus.NOT_RUN) != (outcome == PlanOutcome.NEEDS_INPUTS):
            raise ValueError("needs_inputs exactly when the solver did not run.")
        has_plan = status in (SolverStatus.OPTIMAL, SolverStatus.FEASIBLE)
        if has_plan != (proposed is not None):
            raise ValueError("Only optimal/feasible results have a proposed summary.")
        if not has_plan and status != SolverStatus.NOT_RUN and outcome != PlanOutcome.NO_SOLUTION:
            raise ValueError("Infeasible/unknown results have no solution.")
        if proposed is not None:
            if not self.validation_passed:
                raise ValueError("Never publish a proposal that failed validation.")
            if proposed.included_facility_ids != self.baseline_summary.included_facility_ids:
                raise ValueError("Baseline and proposal cover the same facilities.")
            baseline_covered = self.baseline_summary.covered_service_places
            improved = proposed.covered_service_places > baseline_covered
            expected = PlanOutcome.IMPROVED if improved else PlanOutcome.NO_IMPROVEMENT
            if outcome != expected:
                raise ValueError(f"plan_outcome must be {expected} for this proposal.")
        elif self.selected_projects:
            raise ValueError("Selected projects exist only with a proposed plan.")
        if self.baseline_summary.included_facility_ids != self.coverage.included_facility_ids:
            raise ValueError("Summaries cover exactly the included facilities.")
        ids = [p.candidate_id for p in self.selected_projects]
        if ids != sorted(set(ids)):
            raise ValueError("selected_projects must be ordered by unique candidate_id.")
        totals = (sum(p.capital_cost_minor_units for p in self.selected_projects),
                  sum(p.operating_cost_minor_units for p in self.selected_projects))
        if totals != (self.total_capital_cost_minor_units,
                      self.total_operating_cost_minor_units) or (
            self.total_cost_minor_units != sum(totals)
        ):
            raise ValueError("Cost totals must equal the selected projects.")
        return self


